//! SSE event-stream endpoints.
//!
//! Two routes are mounted here:
//!
//! - `GET /events/sandboxes` — all sandbox-related events in the team's
//!   namespace.
//! - `GET /events/sandboxes/:id` — events for a single sandbox.
//!
//! Each delivered event is a `data: <json>\n\n` SSE frame whose JSON
//! shape is `{ type, reason, message, sandboxID, timestamp }`. The
//! backing data source is `kube::Api<Event>` driven by
//! `kube::runtime::watcher`, filtered to `involvedObject.kind ==
//! "Sandbox"` so unrelated namespace events (Pod scheduling, etc.) are
//! suppressed.
//!
//! The 15s keepalive on the SSE stream keeps intermediate proxies
//! (k8s Ingress, edge LBs) from idle-closing the connection on quiet
//! sandboxes.
//!
//! Routes are wrapped by `auth_middleware` so callers without a valid
//! `X-API-Key` get the same 401 envelope as the lifecycle routes.

use std::{convert::Infallible, sync::Arc, time::Duration};

use axum::{
    extract::{Path, State},
    response::sse::{Event as SseEvent, KeepAlive, Sse},
    routing::get,
    Extension, Router,
};
use futures::{Stream, StreamExt};
use k8s_openapi::api::core::v1::Event as K8sEvent;
use kube::{
    runtime::{watcher, WatchStreamExt},
    Api,
};
use serde::Serialize;
use tokio_stream::wrappers::ReceiverStream;

use crate::{
    auth::{auth_middleware, TeamContext},
    AppState,
};

/// `involvedObject.kind` value the watcher filters on. Kept as a
/// constant so the spelling matches the CRD's `kind` exactly and a typo
/// can't silently drop every event.
const SANDBOX_KIND: &str = "Sandbox";

/// Buffer size for the watcher → SSE channel. 64 is comfortably above
/// burst sizes we expect for a single sandbox (create, schedule, image
/// pull, ready) while keeping memory bounded if the client stalls.
const CHANNEL_CAPACITY: usize = 64;

/// Keepalive interval for the SSE stream. Tuned below the typical
/// 60s idle-timeout enforced by k8s Ingress / cloud LBs so the
/// connection survives long quiet periods.
const KEEPALIVE_INTERVAL: Duration = Duration::from_secs(15);

/// E2B-compatible JSON wire shape for a single sandbox event.
///
/// Kubernetes events have a much larger surface (`firstTimestamp`,
/// `eventTime`, `series`, `reportingComponent`, etc.) — we project
/// down to the five fields the E2B SDK actually consumes so the wire
/// payload stays small and stable across kube versions.
#[derive(Debug, Serialize)]
struct EventDTO {
    /// `Normal` / `Warning`. Mirrors `Event.type` (renamed because
    /// `type` is a Rust keyword).
    #[serde(rename = "type")]
    kind: String,

    /// CamelCase short tag like `Created`, `Scheduled`, `Killing`.
    reason: Option<String>,

    /// Human-readable description.
    message: Option<String>,

    /// `involvedObject.name` when `kind == "Sandbox"` — i.e. the
    /// `sbx-...` id the SDK already knows.
    #[serde(rename = "sandboxID")]
    sandbox_id: Option<String>,

    /// RFC 3339 timestamp. Prefers `lastTimestamp`; empty string if the
    /// apiserver didn't populate one (rare but possible on synthetic
    /// events generated by older controllers).
    timestamp: String,
}

/// Convert a Kubernetes `Event` into the E2B-shaped `EventDTO`.
///
/// `involvedObject.name` is only forwarded when the kind is `Sandbox`
/// — that way a stray Pod event leaking through the filter (defense in
/// depth) never sets a misleading `sandboxID`.
fn ev_to_dto(ev: K8sEvent) -> EventDTO {
    let sandbox_id = if ev.involved_object.kind.as_deref() == Some(SANDBOX_KIND) {
        ev.involved_object.name.clone()
    } else {
        None
    };

    EventDTO {
        kind: ev.type_.unwrap_or_else(|| "Normal".to_owned()),
        reason: ev.reason,
        message: ev.message,
        sandbox_id,
        timestamp: ev
            .last_timestamp
            .map(|t| t.0.to_rfc3339())
            .unwrap_or_default(),
    }
}

/// Whether a single event should be forwarded given the optional
/// per-sandbox filter.
///
/// Pulled out as a free function so it stays trivially unit-testable
/// without standing up a watcher.
fn event_matches(ev: &K8sEvent, filter_sandbox: Option<&str>) -> bool {
    if ev.involved_object.kind.as_deref() != Some(SANDBOX_KIND) {
        return false;
    }
    match filter_sandbox {
        Some(want) => ev.involved_object.name.as_deref() == Some(want),
        None => true,
    }
}

/// Spawn a background task that pumps `kube::runtime::watcher` output
/// into an `mpsc` channel and return the receiver as an SSE-ready
/// `Stream`.
///
/// `applied_objects()` flattens the watcher's `Event::Applied / Deleted
/// / Restarted` envelope into a flat stream of `K8sEvent` so the
/// downstream filter only has to deal with one shape. Watcher errors
/// are dropped silently — the watcher reconnects on its own; we
/// don't want a transient apiserver hiccup to terminate the SSE
/// connection because the SDK would treat that as a fatal error.
fn watch_events(
    api: Api<K8sEvent>,
    filter_sandbox: Option<String>,
) -> impl Stream<Item = Result<SseEvent, Infallible>> {
    let (tx, rx) = tokio::sync::mpsc::channel(CHANNEL_CAPACITY);

    tokio::spawn(async move {
        let mut stream = watcher(api, watcher::Config::default())
            .applied_objects()
            .boxed();
        while let Some(item) = stream.next().await {
            let Ok(ev) = item else {
                // Watcher errors auto-recover via internal restart.
                continue;
            };
            if !event_matches(&ev, filter_sandbox.as_deref()) {
                continue;
            }
            let dto = ev_to_dto(ev);
            let Ok(json) = serde_json::to_string(&dto) else {
                continue;
            };
            // `send` only fails if the receiver was dropped (client
            // disconnected) — in that case we want this task to exit
            // too. Breaking on error stops the watcher promptly instead
            // of letting it churn against a dead channel.
            if tx.send(SseEvent::default().data(json)).await.is_err() {
                break;
            }
        }
    });

    ReceiverStream::new(rx).map(Ok)
}

/// `GET /events/sandboxes` — stream all sandbox events in the team's
/// namespace.
#[tracing::instrument(skip_all, name = "handler:events::stream_all")]
async fn stream_all(
    State(state): State<AppState>,
    Extension(team): Extension<TeamContext>,
) -> Sse<impl Stream<Item = Result<SseEvent, Infallible>>> {
    let api: Api<K8sEvent> = Api::namespaced(state.kube.clone(), &team.namespace);
    let stream = watch_events(api, None);
    Sse::new(stream).keep_alive(KeepAlive::new().interval(KEEPALIVE_INTERVAL))
}

/// `GET /events/sandboxes/:id` — stream events for a single sandbox.
#[tracing::instrument(skip_all, name = "handler:events::stream_one")]
async fn stream_one(
    State(state): State<AppState>,
    Extension(team): Extension<TeamContext>,
    Path(id): Path<String>,
) -> Sse<impl Stream<Item = Result<SseEvent, Infallible>>> {
    let api: Api<K8sEvent> = Api::namespaced(state.kube.clone(), &team.namespace);
    let stream = watch_events(api, Some(id));
    Sse::new(stream).keep_alive(KeepAlive::new().interval(KEEPALIVE_INTERVAL))
}

/// Build the events router wired with `auth_middleware`.
///
/// Same `Arc::clone(&state.key_store)` pattern as `routes::sandboxes`
/// — the middleware's state type (`Arc<dyn KeyStore>`) needs to be
/// passed in independently of the handler state (`AppState`) so axum's
/// state-matching rules line up.
pub fn router(state: AppState) -> Router {
    let key_store = Arc::clone(&state.key_store);
    Router::new()
        .route("/events/sandboxes", get(stream_all))
        .route("/events/sandboxes/:id", get(stream_one))
        .layer(axum::middleware::from_fn_with_state(
            key_store,
            auth_middleware,
        ))
        .with_state(state)
}

#[cfg(test)]
mod tests {
    use super::*;
    use k8s_openapi::api::core::v1::ObjectReference;
    use k8s_openapi::apimachinery::pkg::apis::meta::v1::Time;
    use serde_json::Value;

    fn sandbox_event(name: &str, reason: &str) -> K8sEvent {
        K8sEvent {
            type_: Some("Normal".to_owned()),
            reason: Some(reason.to_owned()),
            message: Some(format!("{reason} happened")),
            involved_object: ObjectReference {
                kind: Some(SANDBOX_KIND.to_owned()),
                name: Some(name.to_owned()),
                ..Default::default()
            },
            last_timestamp: Some(Time(chrono::Utc::now())),
            ..Default::default()
        }
    }

    #[test]
    fn ev_to_dto_renders_e2b_shape() {
        let ev = sandbox_event("sbx-abc", "Created");
        let dto = ev_to_dto(ev);
        let json: Value = serde_json::to_value(&dto).expect("dto serializes");
        assert_eq!(json["type"], "Normal");
        assert_eq!(json["reason"], "Created");
        assert_eq!(json["sandboxID"], "sbx-abc");
        assert!(json["timestamp"].as_str().unwrap().contains('T'));
    }

    #[test]
    fn ev_to_dto_drops_sandbox_id_when_kind_mismatch() {
        let mut ev = sandbox_event("pod-foo", "Scheduled");
        ev.involved_object.kind = Some("Pod".to_owned());
        let dto = ev_to_dto(ev);
        assert_eq!(dto.sandbox_id, None);
    }

    #[test]
    fn event_matches_filters_by_kind_and_name() {
        let ev = sandbox_event("sbx-1", "Created");
        assert!(event_matches(&ev, None));
        assert!(event_matches(&ev, Some("sbx-1")));
        assert!(!event_matches(&ev, Some("sbx-2")));

        let mut other_kind = ev.clone();
        other_kind.involved_object.kind = Some("Pod".to_owned());
        assert!(!event_matches(&other_kind, None));
    }
}
